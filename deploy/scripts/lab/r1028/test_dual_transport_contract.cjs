'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../../../..');
const backend = fs.readFileSync(path.join(root,'apps/control-api/src/c320_live_lab.rs'),'utf8');
const ui = fs.readFileSync(path.join(root,'web/lab/c320-connection-setup.js'),'utf8');
const html = fs.readFileSync(path.join(root,'web/lab/device-workbench.html'),'utf8');
const start = backend.indexOf('async fn fixed_network_probe(');
const end = backend.indexOf('pub(super) async fn connection_status(',start);
const scope = backend.slice(start,end);
assert(start>0 && end>start);
assert.match(backend, /C320_MANAGEMENT_SSH: &str = "10\.10\.13\.233:321"/);
assert.match(backend, /C320_MANAGEMENT_TELNET: &str = "10\.10\.13\.233:323"/);
assert.match(scope, /strict_private\(&headers, false\)/);
assert.match(scope, /tokio::join!/);
assert.match(scope, /"production_adopted":false,"physical_writes_enabled":false/);
assert.match(scope, /"telnet_authentication_verified":false/);
assert.match(scope, /"ssh_authentication_verified":false/);
assert.match(backend, /stream\.read\(&mut first\)/);
assert.doesNotMatch(scope, /username|password|command|shell|sshpass|CONNECT\s*\{/i);
assert.match(html, /id="ipat-c320-check-network"/);
assert.match(ui, /get\('ipat-c320-check-network'\)/);
assert.match(ui, /data\.ssh\.port!==321\|\|data\.telnet\.port!==323/);
assert.match(ui, /No credentials or OLT commands sent/);
assert.doesNotMatch(ui, /innerHTML\s*=|localStorage|sessionStorage/);
console.log('R1028_FIXED_DUAL_TRANSPORT_NETWORK_ONLY_CONTRACT=PASS');
